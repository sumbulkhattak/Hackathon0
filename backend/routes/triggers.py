"""AI Trigger Routes — generate task files in the vault."""

import logging
from datetime import datetime, timezone

from fastapi import APIRouter, Depends, HTTPException, Query
from sqlalchemy.orm import Session
from pydantic import BaseModel
from typing import Optional

from database import get_db
from models import Order, Product
from services import vault, audit
from services.ai_processor import process_task

logger = logging.getLogger(__name__)

router = APIRouter(prefix="/trigger", tags=["AI Triggers"])


# ─── Schemas ────────────────────────────────────────────────────────────────

class OrderTriggerRequest(BaseModel):
    order_id: int


class InquiryTriggerRequest(BaseModel):
    customer_name: str
    email: str
    subject: str
    message: str
    order_id: Optional[int] = None
    product_id: Optional[int] = None


class InventoryTriggerRequest(BaseModel):
    product_id: Optional[int] = None
    threshold: int = 10


class ProductTriggerRequest(BaseModel):
    name: str
    description: str
    price: float
    category_id: int
    stock: int = 50
    featured: bool = False
    image_url: str = ""


class PriceUpdateTriggerRequest(BaseModel):
    product_id: int
    new_price: float
    reason: str


# ─── 1. ORDER TRIGGER ──────────────────────────────────────────────────────

@router.post("/order")
async def trigger_order(
    req: OrderTriggerRequest,
    db: Session = Depends(get_db),
    auto_process: bool = Query(False, description="Immediately trigger AI processing"),
):
    """Generate a task file when a new order is placed."""
    order = db.query(Order).filter(Order.id == req.order_id).first()
    if not order:
        raise HTTPException(status_code=404, detail=f"Order #{req.order_id} not found")

    now = datetime.now(timezone.utc)
    timestamp = now.strftime("%Y-%m-%d_%H-%M-%S")
    filename = f"ORDER-{order.id}_{timestamp}.md"

    items_lines = ""
    for item in order.items:
        product = db.query(Product).filter(Product.id == item.product_id).first()
        product_name = product.name if product else f"Product #{item.product_id}"
        items_lines += f"| {product_name} | {item.quantity} | ₹{item.price:,.0f} | ₹{item.price * item.quantity:,.0f} |\n"

    content = f"""# New Order Task

## Status: PENDING

| Field | Value |
|-------|-------|
| **Task Type** | Order Processing |
| **Priority** | High |
| **Created** | {now.strftime("%Y-%m-%d %H:%M:%S UTC")} |
| **Order ID** | #{order.id} |
| **Customer** | {order.customer_name} |
| **Email** | {order.email} |
| **Phone** | {order.phone} |
| **Address** | {order.address}, {order.city} |
| **Total** | ₹{order.total:,.0f} |
| **Order Status** | {order.status} |

## Order Items

| Product | Qty | Price | Subtotal |
|---------|-----|-------|----------|
{items_lines}
## Action Required

- [ ] Verify payment received
- [ ] Confirm order with customer via email
- [ ] Prepare items for packaging
- [ ] Assign shipping carrier
- [ ] Update order status to "confirmed"
- [ ] Send tracking details to customer

## Notes

> Auto-generated by Royal Sparkle AI Trigger System.
> This task was created at order placement. Process within 24 hours.
"""

    filepath = vault.write_task_file("Needs_Action", filename, content)

    # Audit logging
    audit.write_audit_entry(
        source="trigger/order",
        action="task.created",
        entity_type="order",
        entity_id=filename,
        details={"order_id": order.id, "customer": order.customer_name, "total": order.total},
        queue="Needs_Action",
        status="PENDING",
    )
    audit.append_daily_log(
        source="trigger/order",
        action="Task Created",
        details=f"ORDER-{order.id} — {order.customer_name} — ₹{order.total:,.0f}",
        status="PENDING",
    )

    result = {
        "status": "task_created",
        "trigger": "order",
        "order_id": order.id,
        "task_file": filename,
        "path": filepath,
    }

    # Auto-process if requested
    if auto_process:
        try:
            process_result = process_task(filename, db)
            result["auto_processed"] = True
            result["process_result"] = process_result
        except Exception as e:
            result["auto_processed"] = False
            result["process_error"] = str(e)

    return result


# ─── 2. INQUIRY TRIGGER ────────────────────────────────────────────────────

@router.post("/inquiry")
async def trigger_inquiry(
    req: InquiryTriggerRequest,
    db: Session = Depends(get_db),
    auto_process: bool = Query(False, description="Immediately trigger AI processing"),
):
    """Generate a reply plan task file for a customer inquiry."""
    now = datetime.now(timezone.utc)
    timestamp = now.strftime("%Y-%m-%d_%H-%M-%S")
    filename = f"INQUIRY_{timestamp}.md"

    # Build context section
    context_lines = ""
    if req.order_id:
        order = db.query(Order).filter(Order.id == req.order_id).first()
        if order:
            context_lines += f"\n### Related Order\n\n"
            context_lines += f"- **Order #{order.id}** — ₹{order.total:,.0f} — Status: {order.status}\n"
            context_lines += f"- Placed: {order.created_at}\n"

    if req.product_id:
        product = db.query(Product).filter(Product.id == req.product_id).first()
        if product:
            context_lines += f"\n### Related Product\n\n"
            context_lines += f"- **{product.name}** — ₹{product.price:,.0f}\n"
            context_lines += f"- Stock: {product.stock} units\n"
            context_lines += f"- Category: {product.category.name if product.category else 'N/A'}\n"

    content = f"""# Customer Inquiry — Reply Plan

## Status: PENDING

| Field | Value |
|-------|-------|
| **Task Type** | Customer Reply |
| **Priority** | Medium |
| **Created** | {now.strftime("%Y-%m-%d %H:%M:%S UTC")} |
| **Customer** | {req.customer_name} |
| **Email** | {req.email} |
| **Subject** | {req.subject} |

## Customer Message

> {req.message}
{context_lines}
## Reply Plan

### Suggested Response Outline

1. **Acknowledge** — Greet the customer and thank them for reaching out
2. **Address** — Directly answer their question about: _{req.subject}_
3. **Resolve** — Provide a clear solution or next step
4. **Follow-up** — Offer additional help and close warmly

### Tone Guidelines

- Warm and professional
- Use customer's first name: **{req.customer_name.split()[0]}**
- Brand voice: elegant, helpful, feminine

## Action Required

- [ ] Draft reply following the plan above
- [ ] Review reply for accuracy
- [ ] Send reply to {req.email}
- [ ] Mark inquiry as resolved
- [ ] Log interaction in CRM

## Notes

> Auto-generated by Royal Sparkle AI Trigger System.
> Respond within 4 hours during business hours.
"""

