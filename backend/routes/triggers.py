# ─── 3. INVENTORY TRIGGER ──────────────────────────────────────────────────

@router.post("/inventory")
async def trigger_inventory(
    req: InventoryTriggerRequest,
    db: Session = Depends(get_db),
    auto_process: bool = Query(False, description="Immediately trigger AI processing"),
):
    """Generate an alert task file for low-stock products."""
    now = datetime.now(timezone.utc)
    timestamp = now.strftime("%Y-%m-%d_%H-%M-%S")

    if req.product_id:
        product = db.query(Product).filter(Product.id == req.product_id).first()
        if not product:
            raise HTTPException(status_code=404, detail=f"Product #{req.product_id} not found")
        low_stock = [product] if product.stock < req.threshold else []
    else:
        low_stock = db.query(Product).filter(Product.stock < req.threshold).all()

    if not low_stock:
        return {
            "status": "no_action_needed",
            "trigger": "inventory",
            "message": f"All products are above the {req.threshold}-unit threshold.",
        }

    filename = f"INVENTORY-ALERT_{timestamp}.md"

    product_rows = ""
    critical_count = 0
    for p in low_stock:
        urgency = "CRITICAL" if p.stock <= 3 else ("LOW" if p.stock <= 7 else "WARNING")
        if p.stock <= 3:
            critical_count += 1
        category_name = p.category.name if p.category else "N/A"
        product_rows += f"| {p.id} | {p.name} | {category_name} | {p.stock} | {urgency} |\n"

    priority = "Critical" if critical_count > 0 else "High"

    content = f"""# Inventory Alert — Low Stock

## Status: PENDING

| Field | Value |
|-------|-------|
| **Task Type** | Inventory Restock |
| **Priority** | {priority} |
| **Created** | {now.strftime("%Y-%m-%d %H:%M:%S UTC")} |
| **Threshold** | {req.threshold} units |
| **Products Affected** | {len(low_stock)} |
| **Critical Items** | {critical_count} |

## Low Stock Products

| ID | Product | Category | Stock | Urgency |
|----|---------|----------|-------|---------|
{product_rows}
## Action Required

- [ ] Review low-stock items above
- [ ] Contact suppliers for restock quotes
- [ ] Place restock orders for CRITICAL items immediately
- [ ] Update expected restock dates in system
- [ ] Consider marking out-of-stock items on website
- [ ] Review sales velocity to adjust reorder quantities

## Restock Priority

1. **Immediate** — Items with 0-3 units (CRITICAL)
2. **This Week** — Items with 4-7 units (LOW)
3. **Monitor** — Items with 8-{req.threshold - 1} units (WARNING)

## Notes

> Auto-generated by Royal Sparkle AI Trigger System.
> Critical items should be restocked within 48 hours.
> Review inventory weekly to prevent stockouts.
"""

    filepath = vault.write_task_file("Needs_Action", filename, content)

    # Audit logging
    audit.write_audit_entry(
        source="trigger/inventory",
        action="task.created",
        entity_type="inventory",
        entity_id=filename,
        details={
            "products_affected": len(low_stock),
            "critical_count": critical_count,
            "threshold": req.threshold,
        },
        queue="Needs_Action",
        status="PENDING",
    )
    audit.append_daily_log(
        source="trigger/inventory",
        action="Task Created",
        details=f"INVENTORY-ALERT — {len(low_stock)} products below {req.threshold} units ({critical_count} critical)",
        status="PENDING",
    )

    result = {
        "status": "task_created",
        "trigger": "inventory",
        "products_affected": len(low_stock),
        "critical_count": critical_count,
        "task_file": filename,
        "path": filepath,
    }

    if auto_process:
        try:
            process_result = process_task(filename, db)
            result["auto_processed"] = True
            result["process_result"] = process_result
        except Exception as e:
            result["auto_processed"] = False
            result["process_error"] = str(e)

    return result


